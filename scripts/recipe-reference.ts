/**
 * Writes the generated documentation, straight from the code so it can't drift from it:
 * - docs/recipes/reference.md: every recipe's bands, colour schemes and things
 * - docs/questions-examples.md: one real picture per recipe, its facts and every question it can answer.
 * Run with `npm run docs:recipes` after changing a recipe or the questions.
 */
import { writeFileSync } from 'fs';

import { LEVELS } from '@/game/difficulty';
import { generateQuestions } from '@/scenes/generateQuestions';
import { generateScene } from '@/scenes/generateScene';
import { RECIPES } from '@/scenes/recipes';
import { TIERS, type ItemDef, type ZoneDef } from '@/scenes/types';

const pct = (f: number) => `${Math.round(f * 1000) / 10}%`;

function habits(item: ItemDef): string {
  const h: string[] = [];
  if (item.tall) h.push('tall anchor (stands at the back, rises above its band)');
  if (item.backRow) h.push('against the back (feet at the back line)');
  if (item.frontRow) h.push('at the front edge');
  if (item.spread) h.push('copies spread one per third, on one line');
  if (item.hangAt !== undefined) h.push(`hangs with its centre ${item.hangAt} × width above the band's bottom`);
  if (item.wide) h.push('may span columns');
  if (item.avoidRug) h.push('never on the rug');
  if (item.mixedColours) h.push('copies may differ in colour on Hard');
  if (item.countable === false) h.push('one only, not counted');
  return h.join('; ') || '–';
}

function zoneRow(z: ZoneDef): string {
  const extras = [
    z.rowSizes && `row sizes ${z.rowSizes.join(' : ')}`,
    z.minGroups && `at least ${z.minGroups} kinds`,
    z.maxGroups && `at most ${z.maxGroups} kinds`,
    z.anchors && `${z.anchors} anchors first`,
    z.flush && 'things stand exactly on its bottom line',
    z.panels && 'things stay inside their own third',
    z.oneWay && 'everything faces one way',
  ].filter(Boolean);
  return `| ${z.label} (\`${z.id}\`) | ${pct(z.top)} – ${pct(z.bottom)} | ${z.surface} | ${z.rows} | ${extras.join('; ') || '–'} |`;
}

const out: string[] = [
  '# Recipe reference',
  '',
  '_Generated by `npm run docs:recipes` from `src/scenes/recipes/`. Do not edit by hand._',
  '',
  'Sizes are the thing\'s width as a fraction of the picture width (never under 44 pt on screen). Bands are fractions of the picture height (0 = top).',
  '',
  '| Tier | Width |',
  '| --- | --- |',
  ...Object.entries(TIERS).map(([tier, [lo, hi]]) => `| ${tier} | ${pct(lo)} – ${pct(hi)} |`),
  '',
  '| Level | Kinds | Most of one kind | View time | Asks about house numbers | Mixed colours |',
  '| --- | --- | --- | --- | --- | --- |',
  ...Object.entries(LEVELS).map(([level, k]) => `| ${level} | ${k.groups} | ${k.maxCount} | ${k.viewSeconds} s | ${k.houseNumbers ? 'yes' : 'no'} | ${k.mixedColours ? 'yes' : 'no'} |`),
  '',
];

for (const recipe of RECIPES) {
  out.push(`## ${recipe.title} (\`${recipe.id}\`)`, '');
  out.push('### Bands', '', '| Band | Height | Surface | Slot rows | Rules |', '| --- | --- | --- | --- | --- |', ...recipe.zones.map(zoneRow), '');
  if (recipe.rug) out.push(`Rug: an oval centred at ${pct(recipe.rug.cx)} across, ${pct(recipe.rug.cy)} down, ${pct(recipe.rug.rx * 2)} wide and ${pct(recipe.rug.ry * 2)} of the height tall.`, '');
  if (recipe.keepClear?.length) out.push(`Keep-clear areas (nothing may cover them): ${recipe.keepClear.length} (building doors and their house numbers).`, '');
  if (recipe.details) out.push('Per-picture details: three houses with different named colours and rising house numbers (see `details` in the recipe).', '');
  out.push('### Colour schemes', '', '| Scheme | Surface colours |', '| --- | --- |');
  for (const v of recipe.variants) out.push(`| ${v.id} | ${Object.entries(v.palette).map(([k, c]) => `${k} \`${c}\``).join(', ')} |`);
  out.push('', `### Things (${recipe.items.length})`, '', '| Thing | Band | Size | Most | Colours | Habits |', '| --- | --- | --- | --- | --- | --- |');
  for (const item of recipe.items) {
    const colours = item.colours ? item.colours.map((c) => c.name).join(', ') : `fixed (\`${item.tone}\`)`;
    out.push(`| ${item.singular} | ${item.zones.join(', ')} | ${item.tier} ${pct(item.size)} | ${item.maxCount} | ${colours} | ${habits(item)} |`);
  }
  out.push('');
}

writeFileSync('docs/recipes/reference.md', out.join('\n'));
console.log('Wrote docs/recipes/reference.md');

// Worked examples: a Medium picture per recipe (fixed seed, iPhone 15 size), its facts and its question pool.
const EXAMPLE_SEED = 20261015;
const EXAMPLE_SIZE = { width: 393, height: 687 };
const ex: string[] = [
  '# Question examples',
  '',
  '_Generated by `npm run docs:recipes`. Do not edit by hand._',
  '',
  `For each recipe: one real Medium picture (seed ${EXAMPLE_SEED}, iPhone 15 picture size), the facts recorded when it was made, and every question \`generateQuestions\` writes from them. The answer is marked ✓; in the game the four options are shuffled, and a round picks 5 of these (see [Questions](questions.md#5-picking-the-5-for-a-round)).`,
  '',
];
for (const recipe of RECIPES) {
  const scene = generateScene(recipe, LEVELS.medium, EXAMPLE_SEED, EXAMPLE_SIZE);
  const questions = generateQuestions(scene, recipe, LEVELS.medium);
  const zoneLabel = (id: string) => recipe.zones.find((z) => z.id === id)!.label;
  ex.push(`## ${recipe.title}`, '', `Scene \`${scene.id}\`, colour scheme \`${scene.variantId}\`.`, '', '### Facts', '', '| Thing | Count | Colour | Band | Side |', '| --- | --- | --- | --- | --- |');
  for (const g of scene.groups) {
    const item = recipe.items.find((i) => i.kind === g.kind)!;
    const colour = g.colours ? g.colours.map((c) => c.name).join(' + ') : (g.colour?.name ?? `fixed`);
    const side = item.spread && g.count > 1 ? 'spread (not asked)' : g.region;
    ex.push(`| ${g.count > 1 ? item.plural : item.singular} | ${g.count} | ${colour} | ${zoneLabel(g.zoneId)} | ${side} |`);
  }
  if (scene.details?.houses) {
    ex.push('', 'Houses, left to right: ' + scene.details.houses.map((h) => `${h.colour.name} ${h.number}`).join(', ') + '.');
  }
  ex.push('', `### Questions (${questions.length})`, '', '| Type | Question | Options (✓ = answer) | Subject |', '| --- | --- | --- | --- |');
  for (const q of questions) {
    const options = q.options.map((o, i) => (i === q.answerIndex ? `**✓ ${o}**` : o)).join(' · ');
    ex.push(`| ${q.type} | ${q.prompt} | ${options} | ${q.subject ?? ''} |`);
  }
  ex.push('');
}
writeFileSync('docs/questions-examples.md', ex.join('\n'));
console.log('Wrote docs/questions-examples.md');
